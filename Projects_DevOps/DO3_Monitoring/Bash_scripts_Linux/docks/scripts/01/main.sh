#!/bin/bash

# Проверяем, что передан ровно один аргумент
if [ $# -ne 1 ]; then
    echo "Ошибка: Скрипт должен быть запущен с одним параметром"
    exit 1
fi

param="$1"

# Проверяем, является ли параметр числом
# Корректные форматы:
# 1. Целые числа: 123, +456, -789
# 2. Десятичные дроби с точкой: 12.34, -56.78, .45, +.67
# 3. Десятичные дроби с запятой: 12,34, -56,78, ,45, +,67
# 4. Числа с точкой/запятой в конце: -10. +10,
# Некорректные форматы: 123,.45, 12.34.56, 12,34,56 или просто . , + - т.д.
if [[ $param =~ ^[+-]?([0-9]+|[0-9]*[.,][0-9]+|[0-9]+[.,])$ ]] && [[ ! $param =~ ^[+-]?[.,]$ ]]; then
    echo "Ошибка: недопустимый ввод. Параметр не должен быть числом"
    exit 1
else
    echo "$param"
fi